const VOWELS = new Set(['A', 'E', 'I', 'O', 'U']);

export function countWordConsonantsAndVowels(rawWord: string): {
  consonants: number;
  vowels: number;
  length: number;
} {
  const clean = rawWord.trim().toUpperCase().replace(/[^A-Z]/g, '');
  let vowels = 0;
  let consonants = 0;
  for (let i = 0; i < clean.length; i++) {
    if (VOWELS.has(clean[i])) vowels++;
    else consonants++;
  }
  return { consonants, vowels, length: clean.length };
}

function stripSelfLeak(explanation: string, cleanWord: string): string {
  const escaped = cleanWord.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
  const rx = new RegExp(`\\b${escaped}[a-z]*\\b`, 'gi');
  return explanation.replace(rx, 'this word');
}

function buildMorphologyExplanation(word: string, categoryName?: string): string {
  const clean = word.trim().toUpperCase();
  const catLabel = categoryName ? `${categoryName} ` : '';
  if (clean.endsWith('ING')) {
    return `${catLabel}action word ending with -ING describing ongoing motion or effort`;
  }
  if (clean.endsWith('TION') || clean.endsWith('MENT')) {
    return `${catLabel}noun naming an outcome, process, or clear state of action`;
  }
  if (clean.endsWith('NESS') || clean.endsWith('ITY')) {
    return `${catLabel}abstract quality noun capturing a distinct trait or condition`;
  }
  if (clean.endsWith('ABLE') || clean.endsWith('IBLE')) {
    return `${catLabel}descriptive adjective meaning capable of or worthy of being done`;
  }
  if (clean.endsWith('ER') || clean.endsWith('OR')) {
    return `${catLabel}agent noun or comparative form tied to everyday craft or action`;
  }
  if (clean.endsWith('LY')) {
    return `${catLabel}descriptive adverb explaining the clear manner an action unfolds`;
  }
  if (clean.endsWith('ED')) {
    return `${catLabel}completed past action or seasoned adjective form`;
  }
  if (clean.endsWith('S') && clean.length >= 4 && !clean.endsWith('SS')) {
    return `${catLabel}plural or present-tense vocabulary term linking smoothly across rows`;
  }

  const startsWith = clean[0];
  const { vowels } = countWordConsonantsAndVowels(clean);
  const vowelNote =
    vowels >= 3
      ? 'vowel-rich everyday English term'
      : vowels === 1
      ? 'crisp consonant-heavy English word'
      : 'balanced classic English vocabulary word';
  return `${catLabel}${vowelNote} used naturally in conversation and puzzles (starts with "${startsWith}")`;
}

/**
 * Generates the exact clue style requested by the user:
 *   "3 consonants, 2 vowels — Fluffy sky mass of mist responsible for rain"
 */
export function buildConsonantVowelMeaningClue(
  rawWord: string,
  categoryName?: string
): {
  word: string;
  consonants: number;
  vowels: number;
  patternSummary: string;
  explanation: string;
  fullClue: string;
} {
  const word = rawWord.trim().toUpperCase().replace(/[^A-Z]/g, '');
  const { consonants, vowels } = countWordConsonantsAndVowels(word);
  const patternSummary = `${consonants} ${consonants === 1 ? 'consonant' : 'consonants'}, ${vowels} ${
    vowels === 1 ? 'vowel' : 'vowels'
  }`;

  const curated = CURATED_WORD_MEANINGS[word];
  const rawExplanation = curated || buildMorphologyExplanation(word, categoryName);
  const explanation = stripSelfLeak(rawExplanation, word);
  const fullClue = `${patternSummary} — ${explanation}`;

  return {
    word,
    consonants,
    vowels,
    patternSummary,
    explanation,
    fullClue,
  };
}
